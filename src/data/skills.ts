const SKILL_BY_ID = new Map(SKILLS.map((skill) => [skill.id, skill]));
const SKILL_BY_SEARCH_VALUE = new Map(
  SKILLS.flatMap((skill) =>
    [skill.name, ...(skill.keywords ?? [])].map(
      (value) => [value.toLowerCase(), skill] as const,
    ),
  ),
);

export function getSkillById(id: string) {
  return SKILL_BY_ID.get(id);
}

export function findSkillByName(name: string) {
  const normalized = name.trim().toLowerCase();
  return SKILL_BY_SEARCH_VALUE.get(normalized);
}

export function skillMatchesQuery(skill: SkillDefinition, query: string) {
  const normalizedQuery = query.trim().toLowerCase();
  if (!normalizedQuery) return true;

  return [skill.name, skill.category, ...(skill.keywords ?? [])].some((value) =>
    value.toLowerCase().includes(normalizedQuery),
  );
}
