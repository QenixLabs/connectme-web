const PROVIDER_SKILL_BY_NAME = new Map(
  PROVIDER_SKILLS.map((skill) => [skill.name.toLowerCase(), skill]),
);

export function findProviderSkill(name: string) {
  return PROVIDER_SKILL_BY_NAME.get(name.trim().toLowerCase());
}

export function searchProviderSkills(query: string) {
  const normalizedQuery = query.trim().toLowerCase();
  return PROVIDER_SKILLS.filter((skill) =>
    skill.name.toLowerCase().includes(normalizedQuery),
  );
}
